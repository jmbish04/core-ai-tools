/**
 * @fileoverview `cocreate_generations` — every image a co-creator session
 * produced, and every slot that failed. One row per requested image; a click on
 * "Generate" is one `batch_id`.
 *
 * The Cloudflare Images URL is NOT copied here: it lives on `library_images`
 * (`delivery_url`), one join away, so the two can never disagree. The FK is
 * RESTRICT because library images are soft-delete only.
 */

import { index, integer, sqliteTable, text } from "drizzle-orm/sqlite-core";
import { createInsertSchema, createSelectSchema } from "drizzle-zod";

import { libraryImages } from "../library/images";
import { cocreatePromptVersions } from "./prompt-versions";
import { cocreateSessions } from "./sessions";

export const COCREATE_GENERATIONS_TABLE_DESCRIPTION =
  "Images generated by a co-creator session, each tied to the exact prompt version used. Image URL derives from library_images.";

export const COCREATE_GENERATIONS_COLUMN_DESCRIPTIONS: Record<string, string> = {
  id: "UUID primary key.",
  session_id: "FK cocreate_sessions.id (CASCADE).",
  prompt_version_id: "FK cocreate_prompt_versions.id — the prompt that produced it (CASCADE).",
  library_image_id: "FK library_images.id (RESTRICT) — the stored Cloudflare Images row; null when the slot failed.",
  batch_id: "Groups the images of one Generate click.",
  model: "Model id that served the request.",
  aspect_ratio: "Aspect ratio requested.",
  error: "Provider error for a failed slot, or null.",
  created_at: "Unix timestamp (seconds).",
};

export const cocreateGenerations = sqliteTable(
  "cocreate_generations",
  {
    id: text("id")
      .primaryKey()
      .$defaultFn(() => crypto.randomUUID()),
    sessionId: text("session_id")
      .notNull()
      .references(() => cocreateSessions.id, { onDelete: "cascade" }),
    promptVersionId: text("prompt_version_id")
      .notNull()
      .references(() => cocreatePromptVersions.id, { onDelete: "cascade" }),
    libraryImageId: text("library_image_id").references(() => libraryImages.id, { onDelete: "restrict" }),
    batchId: text("batch_id").notNull(),
    model: text("model").notNull(),
    aspectRatio: text("aspect_ratio"),
    error: text("error"),
    createdAt: integer("created_at", { mode: "timestamp" })
      .notNull()
      .$defaultFn(() => new Date()),
  },
  (t) => [
    index("idx_cocreate_generations_session").on(t.sessionId, t.createdAt),
    index("idx_cocreate_generations_version").on(t.promptVersionId),
    index("idx_cocreate_generations_image").on(t.libraryImageId),
  ],
);

export const insertCocreateGenerationSchema = createInsertSchema(cocreateGenerations);
export const selectCocreateGenerationSchema = createSelectSchema(cocreateGenerations);
export type CocreateGeneration = typeof cocreateGenerations.$inferSelect;
export type NewCocreateGeneration = typeof cocreateGenerations.$inferInsert;
